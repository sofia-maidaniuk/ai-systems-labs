def build_creative_prompt(
    brief: dict,
    segments: list[dict],
    hook: dict,
    price_facts: list[str],
    notes: str = "",
) -> str:
    context = {
        "brief": brief,
        "audience_segments": segments,
        "selected_hook": hook,
        "price_facts": price_facts,
    }

    if notes.strip():
        context["user_comments"] = notes.strip()

    return (
        "Зроби один готовий текст статичного креативу "
        "для вибраного хука.\n\n"
        + json.dumps(
            context,
            ensure_ascii=False,
            separators=(",", ":"),
        )
    )


def build_creative_revision_prompt(
    brief: dict,
    segments: list[dict],
    creative: dict,
    price_facts: list[str],
    feedback: str,
    notes: str = "",
) -> str:
    context = {
        "brief": brief,
        "audience_segments": segments,
        "current_creative": creative,
        "price_facts": price_facts,
    }

    if notes.strip():
        context["advertising_notes"] = notes.strip()

    return (
        "Внеси тільки зазначені користувачем зміни.\n"
        "Усі інші поля скопіюй дослівно.\n\n"
        "Поточний креатив та контекст:\n"
        + json.dumps(
            context,
            ensure_ascii=False,
            separators=(",", ":"),
        )
        + "\n\nПРАВКА КОРИСТУВАЧА:\n"
        + feedback.strip()
        + "\n\nВиконай лише цю правку. "
        "Не переписуй інші частини креативу."
    )